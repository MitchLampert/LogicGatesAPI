namespace MSLLogicGatesSampleClient
{
    /// <summary>
    /// Interaction logic for MainWindow.xaml
    /// </summary>
    public partial class MainWindow : Window
    {
        public MainWindow()
        {
            InitializeComponent();
        }

        private void Window_Loaded(object sender, RoutedEventArgs e)
        {
            MainLogicBoardCtrl.InitializeBitMapCache();
            MainLogicBoardCtrl.LoadAllGameBoardContent(File.ReadAllText("TestAPIComponents.txt"));
        }

        private void BtnPower_Click(object sender, RoutedEventArgs e)
        {
            MainLogicBoardCtrl.TogglePowerFlow();
        }

        private void Window_SizeChanged(object sender, SizeChangedEventArgs e)
        {
            MainLogicBoardCtrl.RedrawTheWholeGameBoard();   
        }
    } //Window Class
} //Namespace